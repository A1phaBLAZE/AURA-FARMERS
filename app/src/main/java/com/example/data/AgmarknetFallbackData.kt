    fun filterRecords(filters: AgmarknetFilters): List<AgmarknetMandiRecord> {
        val stateFilter = filters.state.trim()
        val districtFilter = filters.district.trim()
        val marketFilter = filters.market.trim().lowercase()
        val commodityFilter = filters.commodity.trim().lowercase()
        val varietyFilter = filters.variety.trim().lowercase()

        return officialAgmarknetRecords.filter { record ->
            val matchesState = stateFilter.isBlank() ||
                    stateFilter.equals("All", ignoreCase = true) ||
                    stateFilter.equals("All States", ignoreCase = true) ||
                    record.state.equals(stateFilter, ignoreCase = true)

            val matchesDistrict = districtFilter.isBlank() ||
                    districtFilter.equals("All Districts", ignoreCase = true) ||
                    districtFilter.equals("All", ignoreCase = true) ||
                    record.district.equals(districtFilter, ignoreCase = true)

            val matchesMarket = marketFilter.isBlank() ||
                    marketFilter.equals("all", ignoreCase = true) ||
                    record.market.lowercase().contains(marketFilter)

            val matchesCommodity = commodityFilter.isBlank() ||
                    commodityFilter.equals("all commodities", ignoreCase = true) ||
                    commodityFilter.equals("all", ignoreCase = true) ||
                    record.commodity.lowercase().contains(commodityFilter) ||
                    commodityFilter.contains(record.commodity.lowercase())

            val matchesVariety = varietyFilter.isBlank() ||
                    varietyFilter.equals("all", ignoreCase = true) ||
                    record.variety.lowercase().contains(varietyFilter)

            matchesState && matchesDistrict && matchesMarket && matchesCommodity && matchesVariety
        }.sortedWith(
            compareByDescending<AgmarknetMandiRecord> { it.arrivalTimestamp }
                .thenBy { it.state }
                .thenBy { it.market }
                .thenBy { it.commodity }
        )
    }
