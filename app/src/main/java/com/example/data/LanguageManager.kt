package com.example.data

import com.example.data.model.AppLanguage

object LanguageManager {
    fun getString(key: String, lang: AppLanguage): String {
        val keyMap = translations[key]
        if (keyMap != null) {
            val translated = keyMap[lang]
                ?: keyMap[AppLanguage.HI]
                ?: keyMap[AppLanguage.EN]
            if (!translated.isNullOrBlank()) return translated
        }
        return formatFallbackKey(key)
    }

    fun formatFallbackKey(key: String): String {
        if (!key.contains("_") && !key.contains("-")) return key
        return key.replace("-", "_")
            .split('_')
            .filter { it.isNotBlank() }
            .joinToString(" ") { word ->
                word.lowercase().replaceFirstChar { if (it.isLowerCase()) it.titlecase(java.util.Locale.ROOT) else it.toString() }
            }
    }

